/**
 * Normalized token usage reported by a language model for a single completion. Values are mapped
 * from the underlying API response so callers don't have to special-case the differences between
 * the Chat Completions API (`prompt_tokens` / `completion_tokens`) and the Responses API
 * (`input_tokens` / `output_tokens`).
 */
export type TokenUsage = {
    /**
     * Number of tokens consumed by the prompt/input.
     */
    promptTokens: number;
    /**
     * Number of tokens generated in the completion/output.
     */
    completionTokens: number;
    /**
     * Total number of tokens billed for the request (prompt + completion).
     */
    totalTokens: number;
    /**
     * Prompt tokens that were served from cache (a subset of `promptTokens`), when the API reports
     * it. Cached input tokens are typically billed at a reduced rate.
     */
    cachedPromptTokens?: number;
    /**
     * Reasoning tokens generated by a reasoning model such as o1/o3 (a subset of `completionTokens`),
     * when the API reports it.
     */
    reasoningTokens?: number;
};

/**
 * Normalized reason a completion stopped generating, mapped from the underlying API so callers can
 * detect conditions such as truncation (`"length"`) or filtered output (`"content_filter"`) without
 * special-casing each API variant. `"other"` covers any provider-specific reason that doesn't map to
 * one of the common values.
 */
export type CompletionFinishReason = "stop" | "length" | "content_filter" | "tool_calls" | "other";

/**
 * Metadata about a successful completion. This combines what the language model API reported (token
 * usage, model, finish reason, and the raw response) with TypeChat's own translation metrics (the
 * number of repair attempts). It is attached to the optional `info` property of a `Success` so
 * callers can inspect these details (for example, to track cost or telemetry) without changing how
 * existing results are consumed.
 */
export type CompletionInfo = {
    /**
     * The model that actually produced the completion, as reported by the API. This can differ from
     * the requested model (for example, when an alias resolves to a dated model version).
     */
    model?: string;
    /**
     * Normalized token usage for the request, when the API reports it.
     */
    usage?: TokenUsage;
    /**
     * Normalized reason the completion stopped, when the API reports it.
     */
    finishReason?: CompletionFinishReason;
    /**
     * The raw, unmodified response body returned by the API. Use this to access provider- or
     * API-specific fields (such as `id`, `created`, or `system_fingerprint`) that are not normalized
     * onto the other properties.
     */
    raw?: Record<string, unknown>;
    /**
     * The number of repair attempts TypeChat made before producing this result (`0` when the first
     * response validated). This is populated by `createJsonTranslator`, not by the language model,
     * so it is only present on results returned from `translate`.
     */
    repairAttempts?: number;
};

/**
 * An object representing a successful operation with a result of type `T`.
 */
export type Success<T> = { success: true, data: T, info?: CompletionInfo };

/**
 * An object representing an operation that failed for the reason given in `message`.
 */
export type Error = { success: false, message: string };

/**
 * An object representing a successful or failed operation of type `T`.
 */
export type Result<T> = Success<T> | Error;

/**
 * Returns a `Success<T>` object.
 * @param data The value for the `data` property of the result.
 * @param info Optional language model completion metadata (such as token usage) to attach to the
 *   result via its `info` property. When omitted, no `info` property is added.
 * @returns A `Success<T>` object.
 */
export function success<T>(data: T, info?: CompletionInfo): Success<T> {
    return info ? { success: true, data, info } : { success: true, data };
}

/**
 * Returns an `Error` object.
 * @param message The value for the `message` property of the result.
 * @returns An `Error` object.
 */
export function error(message: string): Error {
    return { success: false, message };
}

/**
 * Obtains the value associated with a successful `Result<T>` or throws an exception if
 * the result is an error.
 * @param result The `Result<T>` from which to obtain the `data` property.
 * @returns The value of the `data` property.
 */
export function getData<T>(result: Result<T>) {
    if (result.success) {
        return result.data;
    }
    throw new Error(result.message);
}
